import CoreGraphics

/// 悬浮面板（覆盖层工具条 / 钉图控制条 / 倒计时 / 编辑器工具条）的背景材质（ticket 17）。
///
/// ## 为什么"选哪种材质"要放在 Core
///
/// 真正的分叉点在 `if #available(macOS 26.0, *)` 上，而**我手上不一定有 26 的系统**。
/// 把"可用性"作为**入参**传进来，"26 用玻璃、15 用 HUD 材质"这条规则就能脱机单测，
/// 不必等到在 26 的机器上肉眼验。
///
/// 视图侧只做一件事：`ChromeMaterial.resolved(glassAvailable: isGlassAvailable).build(cornerRadius:)`。
public enum ChromeMaterial: String, CaseIterable, Sendable {

    /// macOS 26+ 的原生 Liquid Glass（`NSGlassEffectView`）。
    case glass

    /// 15.x 降级：`NSVisualEffectView` 的 `.hudWindow` 材质。
    ///
    /// 选它而不是 `.popover` / `.menu`：那两种是**浅色**材质，
    /// 而这块面板要压在任意屏幕内容上、并且始终是深色的（文字是白的）。
    /// 深色材质在浅色模式下被系统切换掉的表现是"文字突然看不见了"，
    /// 而 `.hudWindow` 在两种外观下都是深的。
    case hud

    /// **「降低透明度」打开时的回退**：实色 `--c-panel`，一点模糊都不做。
    ///
    /// ## 为什么它必须是第三种、而不能复用 `.hud`
    ///
    /// `.hud` 是 `NSVisualEffectView` —— 它**照样半透明**。把它当成无障碍回退，
    /// 等于对一个明确说了"我看不清半透明底"的用户回答"给你换一种半透明"。
    /// 而这个开关的用户往往就是我们最赔不起的那一类（低视力 / 高对比度需求）。
    ///
    /// 稿子 ⑩ §07 把这条写成了规则：「一开，全部 `.glass` 切回 `--c-panel` 不透明 ——
    /// **现有 8 份稿的不透明面就是回退稿，不需要第二套设计**」。
    /// 也就是说这套实色材质本来就在仓库里（`ChromePalette.Theme.panel`），
    /// 只是在此之前它扮演的是"默认"，从 ⑩ 起改扮"回退"。
    case opaque

    /// 按"玻璃是否可用 / 用户是否要求降低透明度"决定用哪种。**唯一的决策点**。
    ///
    /// ⚠️ **降低透明的优先级高于"玻璃可用"**：26 的机器上玻璃可用，
    /// 但用户开了那个开关，就该给实色。两条判据顺序写反的话，
    /// 症状是"这个开关在旧系统上有效、在新系统上没反应"—— 而新系统才是主流。
    public static func resolved(glassAvailable: Bool,
                               reduceTransparency: Bool = false) -> ChromeMaterial {
        if reduceTransparency { return .opaque }
        return glassAvailable ? .glass : .hud
    }
}

/// 悬浮面板的背景参数。两个分支共用同一套值，
/// 免得"26 上看着挺好、15 上字看不清"这种只在某一台机器上出现的差别。
public enum ChromeStyle {

    /// 15.x（`NSVisualEffectView(.hudWindow)`）那条路的衬底不透明度。
    ///
    /// 材质是半透明的：压在一张纯白网页上时，白字会掉到几乎看不见。
    /// 垫一层黑衬底是"这块面板始终可读"的保证 —— 验收项里就有"两种系统上文字对比度足够"。
    public static let scrimAlpha: CGFloat = 0.35

    /// 26+ **玻璃**的着色强度。**必须明显轻于衬底**。
    ///
    /// ⚠️ 这一条是实测调出来的：初版给 0.6，结果玻璃被压成一块几乎不透光的黑板，
    /// 用户的原话是"要玻璃质感"—— 也就是说**为了让文字更清楚而加的着色，
    /// 恰好把要做的那个效果消掉了**。玻璃的透光感来自"底下画面能透上来"，
    /// 着色一重就没得透。对比度改由 `.regular` 风格自身的自适应 + 这层轻着色共同兜住。
    public static let glassTintAlpha: CGFloat = 0.25

    /// `.opaque` 那条路用的实色。
    ///
    /// 直接引用主题里的 `panel`（`--c-panel`）而不是在这里再写一个十六进制 ——
    /// 稿子 ⑩ §07 那句"现有 8 份稿的不透明面就是回退稿"正是指这一枚色。
    /// 抄一份的话，改了主题而忘了这里，"降低透明度"下就会是一块**和别处不一样的**深灰。
    public static var opaqueFill: ChromePalette.Theme { ChromePalette.dark }

    // MARK: - 与稿子 ⑩ 的关系（2026-10-04）
    //
    // 稿子 ⑩ 给的是一套 **Web 配方**：深色色膜 `oklch(26.5% 0 0 / .72)`
    // + `blur(24px) saturate(160%)`，并用"最坏情况（纯白内容）6.10:1"论证它的可读性下限。
    //
    // 实装走的是**系统原生材质**（上面那两条路），这是刻意的：
    // 26+ 的 `NSGlassEffectView` 会跟着系统外观、辅助功能与桌面风格一起变，
    // 而自绘一层 `blur + 半透明色` 是**在窗口里重新实现一遍系统本来就有的东西**，
    // 代价是它在系统改风格那天不会跟着改。
    //
    // ⇒ 于是两套对比度账**不能互相引用**：
    // 稿子那个 6.10:1 是"α .72 压纯白"算出来的，而原生玻璃的合成结果由系统决定。
    // 这里**不许**把 `glassTintAlpha` 往 .72 上调来"对齐稿子"——
    // α .72 是稿子那套配方的浓度，搬到这里只会把玻璃压成黑板（见上一条的实测）。
    // 原生路上"够不够看得清"只能靠 `.regular` 的自适应 + 实测，不能靠算。

    // MARK: - `readoutAlpha` 的两次决定（留着，因为两次都是真的）
    //
    // **2026-10-03 删掉**：自绘小框的半透明底（0.72）被移除，读数框改成实色 `--c-panel`。
    // 理由不是"改用别的值"，而是那个做法本身有问题：半透明的底会让
    // "读数框里的字够不够亮"取决于屏幕上此刻是什么 ——
    // 黑 72% 压在纯白内容上有 5.02，压在纯黑内容上只剩 2.52，连正文级都不到。
    // （顺带记一笔：那条测试写的是 `alpha >= 0.5`，而 0.72 与 0.5 都能过 ——
    //   它拦得住"忘了设"，拦不住"设得不够"。**断言写成了边界而不是意图**，
    //   于是它给了一件它其实没有提供的保证，见 PITFALLS 98。）
    //
    // **2026-10-04 又改成玻璃**：稿子 ⑩ §07 的回写清单把 `.rd` / `.tip` 与
    // `.bar` / `.strip` / `.pop` 并列写进了玻璃族。上面那份论证**方向是对的，
    // 但它算的是另一种摆法**：读数框贴的是选区**外侧**，压在**暗幕（黑 32%）之上**，
    // 不是直接压在原始内容上 —— 那两条对比度说的是"直接压在内容上"。
    //
    // ⇒ 结论：**这一层不该缓存"读数框要不要不透明"这种决定**。
    // 它随设计变，而代码里能存住的只有当前那一条。真正的依据写在
    // `ChromePalette.Overlay.Readout`（字）与 `SelectionOverlayView.syncNoticeChrome`（底）。
}
